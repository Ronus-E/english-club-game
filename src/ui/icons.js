const cache = new Map();

function offscreenIcon(name) {
  if (cache.has(name)) return cache.get(name);
  const def = ICONS[name];
  if (!def) return null;
  const size = 12;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');
  def.art.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      ctx.fillStyle = def.palette[Number(ch) - 1] || '#fff';
      ctx.fillRect(x, y, 1, 1);
    }
  });
  cache.set(name, canvas);
  return canvas;
}

export function drawIcon(ctx, name, x, y, size, { smoothing = false } = {}) {
  const icon = offscreenIcon(name);
  if (!icon) {
    ctx.fillStyle = '#33406e';
    ctx.fillRect(x, y, size, size);
    return;
  }
  const prev = ctx.imageSmoothingEnabled;
  ctx.imageSmoothingEnabled = smoothing;
  ctx.drawImage(icon, 0, 0, 12, 12, Math.round(x), Math.round(y), Math.round(size), Math.round(size));
  ctx.imageSmoothingEnabled = prev;
}

export function iconNames() { return Object.keys(ICONS); }
